--!strict
local Check = require("./Check")
local ReplayClock = require("../src/shared/ReplayClock")

local SPEEDS = { 1, 0.5, 0.25 }
local HOLD = 1

Check.test("a new clock starts at zero, playing at full speed", function()
	local clock = ReplayClock.new(8)
	Check.eq(clock.time, 0, "time")
	Check.eq(clock.speed, 1, "speed")
	Check.eq(clock.paused, false, "paused")
end)

Check.test("time moves by dt times the speed", function()
	local clock = ReplayClock.new(8)
	ReplayClock.advance(clock, 0.5)
	Check.near(clock.time, 0.5, "full speed")
	clock.speed = 0.25
	ReplayClock.advance(clock, 1)
	Check.near(clock.time, 0.75, "quarter speed")
end)

Check.test("a paused clock stands still", function()
	local clock = ReplayClock.new(8)
	ReplayClock.togglePause(clock)
	ReplayClock.advance(clock, 3)
	Check.eq(clock.time, 0, "time")
end)

Check.test("it is done once the end has held for the hold time", function()
	local clock = ReplayClock.new(8)
	ReplayClock.advance(clock, 8.5)
	Check.eq(ReplayClock.done(clock, HOLD), false, "holding")
	ReplayClock.advance(clock, 0.6)
	Check.eq(ReplayClock.done(clock, HOLD), true, "done")
end)

Check.test("a paused clock is never done, even past the end", function()
	local clock = ReplayClock.new(8)
	ReplayClock.advance(clock, 20)
	ReplayClock.togglePause(clock)
	Check.eq(ReplayClock.done(clock, HOLD), false, "paused")
end)

Check.test("playing again from the end starts over", function()
	local clock = ReplayClock.new(8)
	ReplayClock.advance(clock, 8.5)
	ReplayClock.togglePause(clock)
	ReplayClock.togglePause(clock)
	Check.eq(clock.paused, false, "playing")
	Check.eq(clock.time, 0, "from the start")
end)

Check.test("playing again from the middle carries on", function()
	local clock = ReplayClock.new(8)
	ReplayClock.advance(clock, 3)
	ReplayClock.togglePause(clock)
	ReplayClock.togglePause(clock)
	Check.near(clock.time, 3, "time")
end)

Check.test("seeking goes to that fraction of the clip, inside it", function()
	local clock = ReplayClock.new(8)
	ReplayClock.seek(clock, 0.25)
	Check.near(clock.time, 2, "quarter")
	ReplayClock.seek(clock, 1.5)
	Check.near(clock.time, 8, "past the end")
	ReplayClock.seek(clock, -1)
	Check.near(clock.time, 0, "before the start")
end)

Check.test("the fraction played stays from 0 to 1", function()
	local clock = ReplayClock.new(8)
	ReplayClock.advance(clock, 2)
	Check.near(ReplayClock.fraction(clock), 0.25, "quarter")
	ReplayClock.advance(clock, 10)
	Check.near(ReplayClock.fraction(clock), 1, "holding at the end")
	Check.near(ReplayClock.fraction(ReplayClock.new(0)), 1, "empty clip")
end)

Check.test("the speed button steps through the speeds and wraps round", function()
	Check.eq(ReplayClock.nextSpeed(1, SPEEDS), 0.5, "1 to half")
	Check.eq(ReplayClock.nextSpeed(0.5, SPEEDS), 0.25, "half to quarter")
	Check.eq(ReplayClock.nextSpeed(0.25, SPEEDS), 1, "quarter back to 1")
	Check.eq(ReplayClock.nextSpeed(3, SPEEDS), 1, "unknown speed to the first")
end)

Check.finish("ReplayClock")
